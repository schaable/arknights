// Inventory the checked-in game data, without stopping at the first unknown tag.
// node vn/tools/audit-commands.mjs > vn/COMMANDS.md
import { readdir, readFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { supportedCommands } from '../script.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
async function files(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map((entry) => entry.isDirectory()
    ? files(resolve(dir, entry.name)) : entry.name.endsWith('.txt') ? [resolve(dir, entry.name)] : []))).flat().sort();
}
const roots = (await readdir(resolve(root, 'gamedata'), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory()).map((entry) => `gamedata/${entry.name}/story`).sort();
roots.push('vn/sources/en');
const commands = new Map(), counts = [];
for (const corpus of roots) {
  const sources = await files(resolve(root, corpus));
  counts.push([corpus, sources.length]);
  for (const file of sources) {
    const lines = (await readFile(file, 'utf8')).split(/\r?\n/);
    for (const [index, line] of lines.entries()) {
      const match = /^\s*\[(\w+)(?:\s*\(|\])/.exec(line);
      if (!match) continue; // Bare dialogue and [name=...] / [delay=...] shorthand.
      const name = match[1].toLowerCase();
      const data = commands.get(name) || { count: 0, translated: 0, example: null, args: new Set() };
      data.count++;
      if (corpus === 'gamedata/es_ES/story') data.translated++;
      data.example ||= `${relative(root, file)}:${index + 1}`;
      for (const arg of line.slice(0, line.indexOf(']')).matchAll(/(\w+)\s*=/g)) data.args.add(arg[1].toLowerCase());
      commands.set(name, data);
    }
  }
}
console.log(`# Scene command audit

Generated by \`node vn/tools/audit-commands.mjs > vn/COMMANDS.md\`.
This inventories the local files, not the entire upstream game. Counts include
language counterparts and pinned originals; they are command occurrences, not
distinct stories. Dialogue and argument-only shorthand tags are excluded.

| Corpus | Scripts |
| --- | ---: |`);
for (const [corpus, count] of counts) console.log(`| \`${corpus}\` | ${count} |`);
console.log(`
The translated corpus exercises all five newly implemented commands:
\`charactercutin\`, \`backgroundtween\`, \`showitem\`, \`hideitem\`, \`stopsound\`.
Additional commands below remain gated until their scenes can be validated.
No untranslated scenes were enabled by this change. "Supported" refers to the
command family; compatibility checks can still reject unimplemented variants.

| Command | Status | All occurrences | Spanish occurrences | Example |
| --- | --- | ---: | ---: | --- |`);
for (const [name, data] of [...commands].sort(([a], [b]) => a.localeCompare(b))) {
  console.log(`| \`${name}\` | ${supportedCommands.has(name) ? 'Supported' : 'Needs scene validation'} | ${data.count} | ${data.translated} | \`${data.example}\` |`);
}
console.log(`
## Parameters of additional commands

These are observed parameter names, not an implementation specification.
Particles need an asset/rendering adapter; character movement, newer character
slots, text overlays and volume changes need playback and restoration checks
against scenes using them. A known tag must not silently become a no-op.

| Command | Observed parameters |
| --- | --- |`);
for (const [name, data] of [...commands].sort(([a], [b]) => a.localeCompare(b))) {
  if (!supportedCommands.has(name)) console.log(`| \`${name}\` | ${[...data.args].sort().map((arg) => `\`${arg}\``).join(', ') || '—'} |`);
}
